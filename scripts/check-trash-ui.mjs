// Isolated local server only: never deletes production seed documents.
import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const base=process.env.TRASH_TEST_URL||'http://127.0.0.1:8008';
assert.equal(new URL(base).hostname,'127.0.0.1');
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];
try {
 await page.goto(base);
 await page.locator('button[title="Supplier registration form.pdf"]').click();
 await page.getByRole('button',{name:'Delete file',exact:true}).waitFor();
 await page.getByRole('separator',{name:'Resize document panel',exact:true}).press('Home');
 assert(await page.locator('.document-toolbar').evaluate(el=>el.scrollWidth<=el.clientWidth));
 checks.push('PDF tabs, download and delete fit the minimum 320 px panel');
 await page.locator('button[title="Company details.docx"]').click();
 await page.getByRole('button',{name:'Delete file',exact:true}).click();
 let dialog=page.getByRole('alertdialog');await dialog.waitFor();
 await page.screenshot({path:'test-results/trash-confirm-desktop.png'});
 await dialog.getByRole('button',{name:'Keep file',exact:true}).click();
 assert.equal(await page.locator('button[title="Company details.docx"]').count(),1);
 checks.push('Cancel keeps file visible');
 await page.getByRole('button',{name:'Delete file',exact:true}).click();
 await page.getByRole('button',{name:'Move to Trash',exact:true}).click();
 dialog=page.getByRole('dialog');
 const restore=dialog.getByRole('button',{name:'Restore Company details.docx',exact:true});await restore.waitFor();
 assert.equal(await page.locator('button[title="Company details.docx"]').count(),0);
 assert.equal(await page.locator('.document-panel').count(),0);
 await page.screenshot({path:'test-results/trash-desktop.png'});
 checks.push('Delete removes file, closes preview, updates Trash and file count');
 await page.reload();
 await page.getByRole('button',{name:'Trash 1',exact:true}).click();
 await page.getByRole('button',{name:'Restore Company details.docx',exact:true}).click();
 await page.getByText('No deleted files',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Close file dialog',exact:true}).click();
 await page.locator('button[title="Company details.docx"]').click();
 await page.getByRole('button',{name:'Delete file',exact:true}).waitFor();
 checks.push('Trash survives reload and restore returns source to original folder');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Delete file',exact:true}).click();
 await page.screenshot({path:'test-results/trash-confirm-mobile.png'});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 const box=await page.getByRole('button',{name:'Move to Trash',exact:true}).boundingBox();
 assert(box.x>=0&&box.x+box.width<=390&&box.y+box.height<=844);
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('alertdialog').count(),0);
 checks.push('Mobile confirmation fits viewport; Escape cancels');
 await page.emulateMedia({colorScheme:'dark'});
 await page.getByRole('button',{name:'Delete file',exact:true}).click();
 await page.screenshot({path:'test-results/trash-confirm-dark.png'});
 await page.keyboard.press('Tab');
 assert(await page.getByRole('alertdialog').evaluate(el=>el.contains(document.activeElement)));
 checks.push('Dark confirmation and keyboard focus stay usable');
 assert.deepEqual(errors,[]);
 await writeFile('test-results/trash-browser-checks.json',JSON.stringify({tested_at:new Date().toISOString(),environment:'isolated local copies',checks,console_errors:errors},null,2)+'\n');
 console.log(JSON.stringify({passed:checks.length,checks}));
} finally {await browser.close()}
